"""
p1_deg2.py -- Phase 1 of agent A's lambda2-degree2 retro-check.
[oid:lam2A]  NOT RIGOROUS -- float exploration (mpmath), no interval arithmetic.

Adapted from ../sec3_pilot_d4/p1_fixedpoint.py
(read-only template) by substituting t = x^4 -> t = x^2 throughout
(the classical quadratic-map Cvitanovic-Feigenbaum equation).

Solves g(x) = -alpha*g(g(x/alpha)), g(0)=1, g even (series in x^2):
  g(x) = G(t), t = x^2, G(t) = sum_j a_j t^j, a_0 = 1.

Method: collocation at Chebyshev-type nodes on (0,1] + Newton with analytic
Jacobian (mpmath), continuation in the number of modes N.

Linearisation of the doubling operator on normalised quadratic-symmetric
perturbations R(f)(x) = -alpha_f f(f(x/alpha_f)), alpha_f = -1/f(1):

    (DT phi)(x) = -(phi(1)/g(1)) [g(x) - x g'(x)]
                  - alpha * phi(g(x/alpha)) - alpha * g'(g(x/alpha)) * phi(x/alpha)

In t = x^2 variable (general-degree-p formula specialised to p=2):
    K(t)  = G(t) - 2 t G'(t)
    U(t)  = G(t/alpha^2)
    W(t)  = U(t)^2
    (DT Phi)(t) = -(Phi(1)/G(1)) K(t) - alpha * Phi(W(t))
                  - 2 alpha U(t) G'(W(t)) * Phi(t/alpha^2)

Leading eigenvalue -> delta (Feigenbaum delta, known ~4.6692...); we then
extract lambda2, lambda3 (subleading) by mpmath power iteration + deflation
(float eig of the collocation matrix is ill-conditioned -- not used).

MAIN TRAP addressed here (BRIEF Phase 1): the linearisation spectrum contains
INESSENTIAL "coordinate mode" eigenvalues coming from reparametrisations of x
(candidates for degree 2: 1/alpha =~ 0.3995, 1/alpha^2 =~ 0.1596). We run the
same coordinate-mode diagnostic as the quartic template (unprojected DT acting
on K(t) = G(t) - 2 t G'(t), which is the tangent direction generated by
x -> x(1+eps) infinitesimal rescaling) and report its eigenvalue explicitly,
so lambda2 can be checked against it (different eigenvector => essential).

Output: p1_deg2.json
"""
